export function hydrateIcons(root = document) {
  root.querySelectorAll(".cw-fluent-icon").forEach((span) => {
    if (span.dataset.hydrated) return;
    const cls = Array.from(span.classList).find((c) => c.startsWith("cw-icon-"));
    if (!cls) return;
    const name = cls.replace("cw-icon-", "");
    const svg = ICON_MAP[name];
    if (svg) {
      span.innerHTML = svg;
      span.dataset.hydrated = "true";
    }
  });
}